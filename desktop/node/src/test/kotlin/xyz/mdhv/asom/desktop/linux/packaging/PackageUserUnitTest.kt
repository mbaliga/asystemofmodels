package xyz.mdhv.asom.desktop.linux.packaging

import java.nio.file.Files
import java.nio.file.Path
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import xyz.mdhv.asom.desktop.linux.Report

/**
 * B-LA-4: the deb and the rpm install the USER unit under `/usr/lib/systemd/user/`, where the app lives in the root-owned
 * `/opt/asom` (linux.md 3.1, USER row: "`~/.local/opt/asom/<ver>` (tarball) or `/opt/asom` (package)"). The `%h/.local/opt`
 * form is for the tarball installer only; a package that shipped it would run a user-writable binary, or none.
 */
class PackageUserUnitTest {
    private val nfpm: List<String> = Files.readAllLines(Pkg.linux.resolve("nfpm.yaml"))
    private val buildPackages: String = Files.readString(Pkg.linux.resolve("build-packages.sh"))
    private val script: Path = Pkg.linux.resolve("package-user-unit.sh")

    private fun nfpmSrcFor(dst: String): String {
        val i = nfpm.indexOfFirst { it.trim() == "dst: $dst" }
        assertTrue(i > 0, "nfpm.yaml has no entry installing $dst")
        val src = nfpm[i - 1].trim()
        assertTrue(src.startsWith("- src: "), "the line before 'dst: $dst' is not a src: $src")
        return src.removePrefix("- src: ").trim()
    }

    private fun generate(input: Path): Pair<Pkg.Run, Path> {
        val out = Files.createTempFile("asom-pkg-user-", ".service")
        return Pkg.run(listOf("bash", script.toString(), input.toString(), out.toString())) to out
    }

    @Test
    fun `the user unit nfpm installs is not the tarball unit`() {
        val src = nfpmSrcFor("/usr/lib/systemd/user/asom.service")
        assertTrue(!src.endsWith("systemd/asom-user.service"), "nfpm installs the tarball user unit ($src) system-wide")
        assertEquals("\${ASOM_USER_UNIT}", src)
        assertTrue(Regex("for v in [^\\n]*ASOM_USER_UNIT").containsMatchIn(buildPackages), "build-packages.sh does not substitute ASOM_USER_UNIT")
        assertTrue(Regex("export [^\\n]*ASOM_USER_UNIT=").containsMatchIn(buildPackages), "build-packages.sh does not set ASOM_USER_UNIT")
        assertTrue("package-user-unit.sh" in buildPackages, "build-packages.sh does not generate the package unit")
    }

    @Test
    fun `the generated package unit runs the root-owned image and differs from the tarball unit in nothing else`() {
        assertTrue(Files.isRegularFile(script), "$script is missing")
        val (r, out) = generate(Pkg.userUnit)
        assertEquals(0, r.exit, r.out)
        val text = Files.readString(out)
        assertTrue("%h" !in text, "a home-relative path is left in the package unit")
        assertTrue(".local/opt" !in text, "the tarball layout is left in the package unit")
        val s = Pkg.sections(out)
        assertEquals("/opt/asom/current/bin/asom-node --mode=user", s.getValue("Service").filter { it.first == "ExecStart" }.single().second)
        assertEquals("file:/opt/asom/current/share/doc/LINUX.md", s.getValue("Unit").filter { it.first == "Documentation" }.single().second)
        val tarball = Pkg.sections(Pkg.userUnit)
        assertEquals(tarball.keys, s.keys)
        for ((sec, lines) in tarball) {
            val a = lines.filterNot { it.first == "ExecStart" || it.first == "Documentation" }
            val b = s.getValue(sec).filterNot { it.first == "ExecStart" || it.first == "Documentation" }
            assertEquals(a, b, "[$sec] differs beyond the two path lines")
        }
        Report.line("package user unit generated by package-user-unit.sh: ExecStart and Documentation name /opt/asom, every other directive equals asom-user.service (LAB)")
    }

    @Test
    fun `the generator refuses an input that no longer has the lines it rewrites`() {
        assertTrue(Files.isRegularFile(script), "$script is missing")
        val bad = Files.createTempFile("asom-user-bad-", ".service")
        Files.writeString(bad, Files.readString(Pkg.userUnit).replace("ExecStart=%h/.local/opt/asom/current/bin/asom-node --mode=user", "ExecStart=/somewhere/else --mode=user"))
        val (r, out) = generate(bad)
        assertTrue(r.exit != 0, "the generator accepted a unit whose ExecStart it could not rewrite: ${r.out}")
        assertTrue(!Files.exists(out) || Files.size(out) == 0L, "a partial package unit was left behind")
    }
}
