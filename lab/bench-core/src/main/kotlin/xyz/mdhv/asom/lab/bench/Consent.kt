package xyz.mdhv.asom.lab.bench

import java.security.MessageDigest
import java.util.concurrent.atomic.AtomicBoolean

/** Why a run was refused or stopped (benchmark.md 11.2 reason codes and 6.4 / 11.3 abort reasons). */
enum class PreflightReason {
    NO_ENGINE, MODELS_MISSING, STORAGE, TOO_WARM, POWER_SAVER, NEEDS_CHARGER, BATTERY_LOW, BATTERY_WARM, DEVICE_BUSY, SERVING,
    NOT_FOREGROUND, NOT_ENOUGH_MEMORY, VIRTUALIZED, NO_THERMAL_SIGNAL,

    /** Lab-defined (not in the 11.2 table): the platform has no row in 11.3, so no ceiling could stop the run (R4-B-02). */
    NO_CEILINGS,
}

class ConsentError(message: String) : IllegalStateException(message)

/**
 * The consent sheet: the exact words shown (benchmark.md 11.1), generated by the core. The UI's Start action must submit the
 * SHA-256 of the text it displayed; that is the only way to mint a [ConsentToken] (rule B5). The text is a pure function of its inputs.
 */
class ConsentSheet private constructor(val plan: RunPlan, val text: String, val t3OptInOffered: Boolean, val rerunTickRequired: Boolean) {
    val textSha256: ByteArray = MessageDigest.getInstance("SHA-256").digest(text.toByteArray(Charsets.UTF_8))

    /**
     * Throws [ConsentError] unless [shownTextSha256] is the hash of [text] (lengths are compared first). A token is valid for 5 minutes and covers
     * exactly one run. The hash is of the unticked sheet, so it cannot bind the ticks: the token carries them (R4-B-07). [ticks] null means the caller
     * reports none. A name the sheet did not offer, or a rerun tick on a sheet that has none, mints nothing. A sheet that needs the rerun tick and does
     * not get it mints a token whose heat test is not permitted.
     */
    fun confirm(shownTextSha256: ByteArray, nowMs: Long, ticks: ConsentTicks? = null): ConsentToken {
        if (shownTextSha256.size != textSha256.size || !MessageDigest.isEqual(shownTextSha256, textSha256)) throw ConsentError("the hash does not match the text that was shown")
        if (ticks != null) {
            if (ticks.optIns.any { it != ConsentTicks.T3 || !t3OptInOffered }) throw ConsentError("an opt-in that the sheet shown did not offer")
            if (ticks.rerunHeatToday && !rerunTickRequired) throw ConsentError("the sheet shown had no rerun tick")
        }
        return ConsentToken(plan.plan, nowMs, ticks?.optIns ?: emptySet(), ticks?.rerunHeatToday ?: false, rerunTickRequired)
    }

    companion object {
        const val TOKEN_TTL_MS: Long = 300_000L

        /** [downloadBytes] is the total of the files still to download (0 when all are present); [tiers] names them. */
        fun forPlan(plan: RunPlan, downloadBytes: Long, tiers: List<String>, t3OptInOffered: Boolean, sustainedToday: Boolean): ConsentSheet {
            val minutes = when (plan.plan) {
                "quick" -> "up to 5"
                "standard" -> "20-30"
                else -> "a few"
            }
            val gb = if (downloadBytes == 0L) "0.0" else TextRender.gb(downloadBytes).removeSuffix(" GB")
            val lines = mutableListOf<String>()
            lines += "Run the ${plan.plan} device test?"
            lines += "- Takes about $minutes minutes. You can stop at any time."
            if (plan.sustain != null) {
                lines += "- Makes the device warm and uses power. Keep it on its charger."
            } else {
                lines += "- Uses power for a few minutes."
            }
            lines += if (downloadBytes == 0L) "- Downloads nothing: the test models are already on this device." else "- Downloads $gb GB of test models over Wi-Fi first (${tiers.joinToString(", ")})."
            if (t3OptInOffered) lines += "  [ ] Also test 8B models (+5.0 GB). Without this, 8B speed is estimated."
            lines += "- Nothing is uploaded. Results stay on this device unless you share them."
            lines += "- If the device gets too hot, the test stops by itself."
            val rerunTick = sustainedToday && plan.sustain != null
            if (rerunTick) lines += "  [ ] Run the heat test again today."
            lines += "[Not now]   [Start]"
            return ConsentSheet(plan, lines.joinToString("\n") + "\n", t3OptInOffered, rerunTick)
        }
    }
}

/** What the user ticked on the sheet (benchmark.md 11.1, 11.6 rule 3). Only `T3` exists as an opt-in name. */
class ConsentTicks(val optIns: Set<String> = emptySet(), val rerunHeatToday: Boolean = false) {
    companion object {
        const val T3 = "T3"
    }
}

/**
 * Covers exactly one run of [planId]; expires [ConsentSheet.TOKEN_TTL_MS] after minting; single use, whoever holds a copy of the reference. It carries
 * the ticks (R4-B-07): the executor reads the opt-in tiers and the rerun tick only from here.
 */
class ConsentToken internal constructor(
    val planId: String,
    val mintedAtMs: Long,
    val optIns: Set<String>,
    val rerunHeatToday: Boolean,
    private val rerunTickWasRequired: Boolean,
) {
    private val spent = AtomicBoolean(false)

    val consumed: Boolean get() = spent.get()

    val expiresAtMs: Long get() = mintedAtMs + ConsentSheet.TOKEN_TTL_MS

    /** False when the sheet needed the "run the heat test again today" tick and it was not ticked: no sustained phase may run. */
    val heatTestPermitted: Boolean get() = !rerunTickWasRequired || rerunHeatToday

    /** A refused spend (another plan, expired) leaves the token unspent. */
    fun consume(planId: String, nowMs: Long) {
        if (planId != this.planId) throw ConsentError("token is for plan ${this.planId}")
        if (nowMs >= expiresAtMs) throw ConsentError("token expired")
        if (!spent.compareAndSet(false, true)) throw ConsentError("token already used")
    }
}
